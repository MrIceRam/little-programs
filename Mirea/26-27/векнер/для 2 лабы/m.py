import numpy as np
import matplotlib.pyplot as plt
from scipy import signal

# ------------------------------------------------------------
# Время моделирования
# ------------------------------------------------------------
t = np.linspace(0, 10, 2000)

# ------------------------------------------------------------
# Модель 1: устойчивая исходная система (вариант 13)
# ------------------------------------------------------------
A1 = np.array([
    [-1.0,  2.0, -3.0],
    [ 0.0, -5.0,  1.0],
    [ 2.0,  1.0, -2.0]
])
B1 = np.array([[ 1.0],
               [ 2.0],
               [-1.0]])
C1 = np.array([[ 1.0, 0.0, -3.0]])
D1 = np.array([[0.0]])

# ------------------------------------------------------------
# Модель 2: после перехода к базису P
# ------------------------------------------------------------
A2 = np.array([
    [-7.4,  4.8,  -4.0],
    [-9.2,  8.4, -17.0],
    [-2.2,  3.4,  -9.0]
])
B2 = np.array([[-7.0],
               [ 4.0],
               [ 5.0]])
C2 = np.array([[-3.4, 3.8, -7.0]])
D2 = np.array([[0.0]])

# ------------------------------------------------------------
# Создание моделей в пространстве состояний
# ------------------------------------------------------------
system1 = signal.StateSpace(A1, B1, C1, D1)
system2 = signal.StateSpace(A2, B2, C2, D2)

# ------------------------------------------------------------
# Расчёт переходных характеристик
# ------------------------------------------------------------
t1, y1 = signal.step(system1, T=t)
t2, y2 = signal.step(system2, T=t)

# ------------------------------------------------------------
# График переходных характеристик
# ------------------------------------------------------------
plt.figure(figsize=(9, 5))
plt.plot(t1, y1, label="Исходная устойчивая модель", linewidth=1.8)
plt.plot(t2, y2, "--", label="Модель после преобразования", linewidth=1.8)
plt.xlabel("Время t, с")
plt.ylabel("y(t)")
plt.title("Сравнение переходных характеристик")
plt.grid(True)
plt.legend()
plt.show()

# ------------------------------------------------------------
# Расчёт текущей ошибки
# ------------------------------------------------------------
error = y1 - y2

# Максимальная абсолютная текущая ошибка
max_abs_error = np.max(np.abs(error))

# Интегральное квадратичное отклонение
delta = np.trapezoid(error**2, t)

print("Максимальная абсолютная текущая ошибка: max|ε(t)| =", max_abs_error)
print("Интегральное отклонение delta =", delta)

# ------------------------------------------------------------
# График текущей ошибки
# ------------------------------------------------------------
plt.figure(figsize=(9, 5))
plt.plot(t, error, linewidth=1.2)
plt.xlabel("Время t, с")
plt.ylabel("ε(t)")
plt.title("График текущей ошибки")
plt.grid(True)
plt.show()