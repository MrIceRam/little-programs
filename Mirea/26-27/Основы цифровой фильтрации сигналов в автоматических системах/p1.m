% Оськин Влад КВБО-11-24 Вариант 19 a=0.42, b=7, N=700
clear; clc; close all;
a = 0.42;
b = 7;
N = 700;

%Взял с доски
v = b * rand(1, N);

%Взял с доски x(n)=(1-a)*x(n-1)+a*v(n)
x = zeros(1, N);
x(1) = b / 2;
for n = 2:N
    x(n) = (1 - a) * x(n-1) + a * v(n);
end

%График случайного процесса v(n)
figure;
plot(0:N-1, v);
title('График случайного процесса v(n)');
xlabel('n'); ylabel('v(n)'); grid on;

%Гистограмма распределения v(n) по равномерному закону
Lv = round(sqrt(N));
figure;
hist(v, Lv);
title(sprintf('Гистограмма распределения v(n) по равномерному закону', Lv));
xlabel('Значения v'); ylabel('Частота'); grid on;

%График случайного процесса после прохождения через простой фильтр
figure;
plot(0:N-1, x);
title('График случайного процесса после прохождения через простой фильтр');
xlabel('n'); ylabel('x(n)'); grid on;

%Гистограмма распределения x(n) по нормальному закону
Lx = round(sqrt(N));
figure;
hist(x, Lx);
title(sprintf('Гистограмма распределения x(n) по нормальному закону', Lx));
xlabel('Значения x'); ylabel('Частота'); grid on;

%График оценки автоковариационной функции
M = 32;  % M < N/10 = 70
r = zeros(1, M+1);
mu_x = mean(x);
for m = 0:M
    sum_val = 0;
    for n = 1:(N - m)
        sum_val = sum_val + (x(n) - mu_x) * (x(n + m) - mu_x);
    end
    r(m+1) = sum_val / N;   % смещённая (деление на N)
end
figure;
stem(0:M, r, 'filled');
title('График оценки автоковариационной функции');
xlabel('Сдвиг m'); ylabel('r_x^*(m)'); grid on;

% -------- Вычисление статистик --------
mu_x = mean(x);
D_x = var(x);   % несмещённая
fprintf('Оценка мат. ожидания μx* = %.4f\n', mu_x);
fprintf('Оценка дисперсии Dx* = %.4f\n', D_x);
disp('Гистограмма x(n) показывает распределение, близкое к нормальному (эффект фильтрации).');
